function showScreen(name) {
  Object.values(screens).forEach(screen => {
    screen.classList.remove("active");
  });

  screens[name].classList.add("active");

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

function terminalLine(message, type = "") {
  const line = document.createElement("div");

  line.className = "terminal-line " + type;
  line.textContent = "> " + message;

  $("terminal").appendChild(line);

  while ($("terminal").children.length > 35) {
    $("terminal").firstElementChild.remove();
  }

  $("terminal").scrollTop = $("terminal").scrollHeight;
}

function playTone(frequency = 500, duration = 120) {
  if (!soundEnabled) return;

  try {
    audioContext = audioContext ||
      new (window.AudioContext || window.webkitAudioContext)();

    if (audioContext.state === "suspended") {
      audioContext.resume();
    }

    const oscillator = audioContext.createOscillator();
    const gain = audioContext.createGain();

    oscillator.type = "sawtooth";
    oscillator.frequency.value = frequency;

    gain.gain.setValueAtTime(
      0.035,
      audioContext.currentTime
    );

    gain.gain.exponentialRampToValueAtTime(
      0.001,
      audioContext.currentTime + duration / 1000
    );

    oscillator.connect(gain);
    gain.connect(audioContext.destination);

    oscillator.start();
    oscillator.stop(
      audioContext.currentTime + duration / 1000
    );
  } catch (error) {
    console.warn("Audio unavailable");
  }
}

function vibrate(pattern = 100) {
  if (!vibrationEnabled) return;

  try {
    if (navigator.vibrate) {
      navigator.vibrate(pattern);
    }
  } catch (error) {}
}

function showAlert(title, message) {
  $("alertTitle").textContent = title;
  $("alertMessage").textContent = message;

  $("alertBox").classList.remove("hidden");

  document.body.classList.add("scare");

  playTone(800, 250);
  vibrate([120, 70, 120]);

  clearTimeout(alertTimer);

  alertTimer = setTimeout(() => {
    $("alertBox").classList.add("hidden");
    document.body.classList.remove("scare");
  }, 2800);
}

function updatePhases() {
  const phases = [
    { start: 0, name: "INITIALIZATION" },
    { start: 25, name: "VIRTUAL ANALYSIS" },
    { start: 50, name: "VISUAL SIMULATION" },
    { start: 80, name: "FINAL REPORT" }
  ];

  let current = 0;

  phases.forEach((phase, index) => {
    if (progress >= phase.start) {
      current = index;
    }
  });

  $("phaseName").textContent = phases[current].name;

  for (let i = 1; i <= 4; i++) {
    const status = $("status" + i);
    const phase = status.closest(".phase");

    phase.classList.remove("current", "complete");

    if (i - 1 < current) {
      phase.classList.add("complete");
      status.textContent = "DONE";
    } else if (i - 1 === current) {
      phase.classList.add("current");
      status.textContent = "ACTIVE";
    } else {
      status.textContent = "WAITING";
    }
  }
}

function processCommands() {
  while (
    commandIndex < commands.length &&
    progress >= commands[commandIndex][0]
  ) {
    const command = commands[commandIndex];

    terminalLine(command[1], command[2]);

    if (command[2] === "warning") {
      playTone(750, 180);
    } else {
      playTone(420, 70);
    }

    commandIndex++;
  }
}

function updateProgress() {
  $("percentage").textContent =
    String(progress).padStart(2, "0") + "%";

  $("progressFill").style.width = progress + "%";

  updatePhases();
}

function startExperience() {
  if (running) return;

  currentName = $("target").value.trim();

  if (!currentName) {
    alert("اكتب اسم العرض التجريبي أولاً.");
    $("target").focus();
    return;
  }

  soundEnabled = $("soundToggle").checked;
  vibrationEnabled = $("vibrationToggle").checked;

  progress = 0;
  commandIndex = 0;
  paused = false;
  running = true;

  commands.forEach(command => {
    commandIndex = 0;
  });

  $("displayName").textContent = currentName;
  $("finalName").textContent =
    "يا " + currentName + "، اتعمل فيك مقلب!";

  $("terminal").innerHTML = "";
  $("alertBox").classList.add("hidden");

  $("pauseBtn").textContent = "Ⅱ إيقاف مؤقت";

  updateProgress();

  terminalLine("ALMOZAG HACKER X V1");
  terminalLine("Fictional simulation started.");
  terminalLine("No external devices or networks accessed.");

  showScreen("simulation");

  playTone(500, 100);
  vibrate(100);

  timer = setInterval(runSimulation, 450);
}

function runSimulation() {
  if (!running || paused) return;

  progress = Math.min(
    progress + Math.floor(Math.random() * 3) + 2,
    100
  );

  updateProgress();
  processCommands();

  if (progress >= 43 && progress < 50 &&
      !window.firstAlertShown) {

    window.firstAlertShown = true;

    showAlert(
      "SIMULATED WARNING",
      "تم الوصول إلى مرحلة التنبيه التمثيلي!"
    );
  }

  if (progress >= 73 && progress < 80 &&
      !window.secondAlertShown) {

    window.secondAlertShown = true;

    showAlert(
      "FINAL SIMULATION ALERT",
      "اكتملت معظم مراحل التجربة!"
    );
  }

  if (progress >= 100) {
    completeExperience();
  }
}

function completeExperience() {
  if (!running) return;

  running = false;
  paused = false;

  clearInterval(timer);
  timer = null;

  clearTimeout(alertTimer);

  $("alertBox").classList.add("hidden");

  progress = 100;
  updateProgress();

  terminalLine("SIMULATION COMPLETED", "success");
  terminalLine("No real hacking took place.", "success");

  playTone(650, 300);
  vibrate([100, 70, 180]);

  setTimeout(() => {
    showScreen("reveal");
  }, 1400);
}

function pauseExperience() {
  if (!running) return;

  paused = !paused;

  $("pauseBtn").textContent = paused
    ? "▶ استكمال التجربة"
    : "Ⅱ إيقاف مؤقت";

  if (paused) {
    terminalLine("Simulation paused.");
  } else {
    terminalLine("Simulation resumed.");
    playTone(450, 90);
  }
}

function stopExperience() {
  running = false;
  paused = false;

  clearInterval(timer);
  clearTimeout(alertTimer);

  timer = null;

  $("alertBox").classList.add("hidden");

  if (navigator.vibrate) {
    navigator.vibrate(0);
  }

  terminalLine("Simulation stopped by user.");

  resetToHome();
}

function resetToHome() {
  running = false;
  paused = false;
  progress = 0;
  commandIndex = 0;

  clearInterval(timer);
  clearTimeout(alertTimer);

  timer = null;

  window.firstAlertShown = false;
  window.secondAlertShown = false;

  $("target").value = "";
  $("percentage").textContent = "00%";
  $("progressFill").style.width = "0%";

  $("pauseBtn").textContent = "Ⅱ إيقاف مؤقت";

  $("alertBox").classList.add("hidden");
  document.body.classList.remove("scare");

  for (let i = 1; i <= 4; i++) {
    const status = $("status" + i);

    status.textContent = "WAITING";
    status.closest(".phase").classList.remove(
      "current", "complete"
    );
  }

  showScreen("home");
}

$("startBtn").addEventListener("click", startExperience);

$("pauseBtn").addEventListener("click", pauseExperience);

$("stopBtn").addEventListener("click", stopExperience);

$("againBtn").addEventListener("click", resetToHome);

$("homeBtn").addEventListener("click", resetToHome);

$("target").addEventListener("keydown", event => {
  if (event.key === "Enter") {
    startExperience();
  }
});

// Matrix background
const canvas = $("matrix");
const ctx = canvas.getContext("2d");

const chars = "01ABCDEFGHIJKLMNOPQRSTUVWXYZ#$%";
let drops = [];

function resizeMatrix() {
  const dpr = Math.min(window.devicePixelRatio || 1, 2);

  canvas.width = window.innerWidth * dpr;
  canvas.height = window.innerHeight * dpr;

  canvas.style.width = window.innerWidth + "px";
  canvas.style.height = window.innerHeight + "px";

  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

  drops = Array(
    Math.ceil(window.innerWidth / 17)
  ).fill(1);
}

function drawMatrix() {
  ctx.fillStyle = "rgba(5,0,0,.12)";
  ctx.fillRect(0, 0, window.innerWidth, window.innerHeight);

  ctx.font = "13px monospace";
  ctx.fillStyle = "#ff1717";

  drops.forEach((y, i) => {
    const char = chars[
      Math.floor(Math.random() * chars.length)
    ];

    ctx.fillText(char, i * 17, y * 17);

    if (
      y * 17 > window.innerHeight &&
      Math.random() > 0.975
    ) {
      drops[i] = 0;
    }

    drops[i]++;
  });
}

window.addEventListener("resize", resizeMatrix);

resizeMatrix();

setInterval(drawMatrix, 75);

