
const $ = id => document.getElementById(id);

const terminal = $("terminal");
const startBtn = $("startBtn");
const resetBtn = $("resetBtn");
const progressFill = $("progressFill");
const percent = $("percent");

let running = false;
let timer = null;
let audioEnabled = false;
let audioContext = null;

const commands = [
  "[+] Initializing fictional simulation engine...",
  "[+] Loading visual system modules...",
  "[+] Checking simulated system environment...",
  "[+] Analyzing virtual network...",
  "[+] Generating fictional security report...",
  "[!] Simulated security alert detected!",
  "[+] Running visual diagnostic sequence...",
  "[+] Preparing final simulation report...",
  "[OK] All simulation stages completed."
];

function addLine(message, type = "") {
  const line = document.createElement("div");
  line.className = "terminal-line " + type;
  line.textContent = message;

  const cursor = terminal.querySelector(".cursor");
  if (cursor) {
    terminal.insertBefore(line, cursor);
  } else {
    terminal.appendChild(line);
  }

  terminal.scrollTop = terminal.scrollHeight;
}

function beep(frequency = 500, duration = 100) {
  if (!audioEnabled) return;

  try {
    audioContext = audioContext || new (
      window.AudioContext || window.webkitAudioContext
    )();

    if (audioContext.state === "suspended") {
      audioContext.resume();
    }

    const oscillator = audioContext.createOscillator();
    const gain = audioContext.createGain();

    oscillator.type = "sawtooth";
    oscillator.frequency.value = frequency;
    gain.gain.value = 0.035;

    oscillator.connect(gain);
    gain.connect(audioContext.destination);

    oscillator.start();
    oscillator.stop(audioContext.currentTime + duration / 1000);
  } catch (e) {}
}

function setStep(number) {
  for (let i = 1; i <= 4; i++) {
    const element = $("step" + i);
    element.classList.remove("active", "done");

    if (i < number) element.classList.add("done");
    if (i === number) element.classList.add("active");
  }
}

function updateStats() {
  $("cpu").textContent = Math.floor(20 + Math.random() * 70) + "%";
  $("memory").textContent = Math.floor(30 + Math.random() * 60) + "%";

  $("cpuBar").style.width = $("cpu").textContent;
  $("memoryBar").style.width = $("memory").textContent;
}

function finishSimulation() {
  running = false;
  clearInterval(timer);
  timer = null;

  percent.textContent = "100%";
  progressFill.style.width = "100%";

  setStep(5);

  addLine("[OK] Simulation completed successfully.", "success");
  addLine("[INFO] No real device was accessed.", "success");

  $("terminal").querySelector(".terminal-status")?.remove();

  $("result").classList.remove("hidden");

  $("resultText").textContent =
    "اكتملت محاكاة النظام التجريبية بنجاح.";

  startBtn.disabled = false;
  startBtn.innerHTML = "▶ START SIMULATION";

  beep(750, 250);

  $("result").scrollIntoView({
    behavior: "smooth",
    block: "center"
  });
}

function startSimulation() {
  if (running) return;

  const target = $("target").value.trim();

  if (!target) {
    alert("اكتب اسماً تجريبياً أولاً!");
    $("target").focus();
    return;
  }

  running = true;
  startBtn.disabled = true;
  startBtn.textContent = "SIMULATION RUNNING...";

  $("result").classList.add("hidden");
  $("prank").classList.add("hidden");

  terminal.innerHTML = "";
  addLine("ALMOZAG HACKER X V1");
  addLine("Target label: " + target);
  addLine("Starting fictional simulation...", "warning");

  let progress = 0;
  let commandIndex = 0;

  timer = setInterval(() => {
    if (!running) return;

    progress += Math.floor(Math.random() * 4) + 2;

    if (progress > 100) progress = 100;

    progressFill.style.width = progress + "%";
    percent.textContent = progress + "%";

    updateStats();

    if (progress < 25) {
      setStep(1);
    } else if (progress < 50) {
      setStep(2);
    } else if (progress < 80) {
      setStep(3);
    } else {
      setStep(4);
    }

    if (commandIndex < commands.length) {
      const threshold = commandIndex * 12;

      if (progress >= threshold) {
        const isWarning = commands[commandIndex].includes("[!]");
        addLine(
          commands[commandIndex],
          isWarning ? "warning" : "success"
        );

        beep(isWarning ? 850 : 450, 70);
        commandIndex++;
      }
    }

    if (progress >= 100) {
      finishSimulation();
    }

  }, 450);
}

function resetSimulation() {
  running = false;
  clearInterval(timer);
  timer = null;

  progressFill.style.width = "0%";
  percent.textContent = "0%";

  terminal.innerHTML = `
    <div class="terminal-line">ALMOZAG SYSTEM [VERSION 1.0]</div>
    <div class="terminal-line">Simulation reset successfully.</div>
    <div class="terminal-line">Waiting for user command...</div>
    <div class="cursor">_</div>
  `;

  $("result").classList.add("hidden");
  $("prank").classList.add("hidden");

  for (let i = 1; i <= 4; i++) {
    $("step" + i).classList.remove("active", "done");
  }

  $("cpu").textContent = "34%";
  $("memory").textContent = "62%";
  $("cpuBar").style.width = "34%";
  $("memoryBar").style.width = "62%";

  startBtn.disabled = false;
  startBtn.innerHTML = "▶ START SIMULATION";
}

function revealPrank() {
  $("result").classList.add("hidden");
  $("prank").classList.remove("hidden");

  $("prank").scrollIntoView({
    behavior: "smooth",
    block: "center"
  });

  beep(600, 180);
}

startBtn.addEventListener("click", startSimulation);

resetBtn.addEventListener("click", resetSimulation);

$("revealBtn").addEventListener("click", revealPrank);

$("againBtn").addEventListener("click", () => {
  resetSimulation();
  $("target").value = "";
  window.scrollTo({ top: 0, behavior: "smooth" });
});

$("soundBtn").addEventListener("click", async () => {
  audioEnabled = !audioEnabled;

  $("soundBtn").textContent = audioEnabled
    ? "🔇 إيقاف الصوت"
    : "🔊 تشغيل الصوت";

  if (audioEnabled) {
    beep(600, 100);
  } else if (audioContext) {
    await audioContext.suspend();
  }
});

// Decorative system statistics
setInterval(() => {
  if (!running) updateStats();
}, 3000);

// Matrix background
const canvas = $("matrix");
const ctx = canvas.getContext("2d");

let drops = [];
const chars = "01ABCDEFGHIJKLMNOPQRSTUVWXYZ#$%";

function resizeMatrix() {
  const dpr = Math.min(window.devicePixelRatio || 1, 2);

  canvas.width = window.innerWidth * dpr;
  canvas.height = window.innerHeight * dpr;

  canvas.style.width = window.innerWidth + "px";
  canvas.style.height = window.innerHeight + "px";

  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

  drops = Array(
    Math.ceil(window.innerWidth / 17)
  ).fill(1);
}

function drawMatrix() {
  ctx.fillStyle = "rgba(5,0,0,0.10)";
  ctx.fillRect(0, 0, window.innerWidth, window.innerHeight);

  ctx.fillStyle = "#ff1515";
  ctx.font = "13px monospace";

  drops.forEach((y, i) => {
    const char = chars[
      Math.floor(Math.random() * chars.length)
    ];

    ctx.fillText(char, i * 17, y * 17);

    if (
      y * 17 > window.innerHeight &&
      Math.random() > 0.975
    ) {
      drops[i] = 0;
    }

    drops[i]++;
  });
}

window.addEventListener("resize", resizeMatrix);

resizeMatrix();

setInterval(drawMatrix, 70);
